const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
let commits=0,renders=0;
const ctx=vm.createContext({clearTimeout(){},setTimeout(){},tiles:[{imgId:'a',caption:'A',simLiked:true,commentEntries:[{id:'1',author:'vos',text:'Hola'}]},{imgId:'b',caption:'B'},null],total:3,sel:new Set(),ghost:{style:{}},normalizeBanners(){},render(){renders++},updateExportUI(){},commit(){commits++},clearDrop(){}});
vm.runInContext(fs.readFileSync('dist/simulator.js','utf8'),ctx);
const run=source=>vm.runInContext(source,ctx);
run("studioDrag={kind:'cell',src:0};finishStudioDrop(1)");
assert.equal(ctx.tiles[1].imgId,'a');
assert.equal(ctx.tiles[1].commentEntries[0].text,'Hola');
assert.equal(ctx.tiles[1].simLiked,true);
assert.equal(ctx.tiles[0].imgId,'b');
assert.equal(commits,1);assert.equal(renders,1);
run("studioDrag={kind:'cell',src:1};finishStudioDrop(2)");
assert.equal(ctx.tiles[1],null);assert.equal(ctx.tiles[2].caption,'A');
run("studioDrag={kind:'cell',src:2};finishStudioDrop(-1)");
assert.equal(ctx.tiles[2].imgId,'a');assert.equal(commits,2);
assert.equal(run("simLikeCount({likes:'1200',simLiked:true})"),'1201');
assert.equal(run("simLikeCount({likes:'12,5 mil',simLiked:false})"),'12,5 mil');
assert.equal(run("storyItems({stories:[{src:'a'},{src:'b'}]}).length"),2);
assert.equal(run("storyItems({stories:[]}).length"),0);
ctx.lib=[{id:'a'},{id:'b'},{id:'c'}];ctx.tiles=[{imgId:'a'},null,{imgId:'missing'},{imgId:'b'},null,{imgId:'c'}];
assert.equal(JSON.stringify(run('simPostNavigation(0)')),JSON.stringify({previous:null,next:3}),'Post navigation skips empty slots and unavailable assets');
assert.equal(JSON.stringify(run('simPostNavigation(3)')),JSON.stringify({previous:0,next:5}));
assert.equal(JSON.stringify(run('simPostNavigation(5)')),JSON.stringify({previous:3,next:null}),'Last post has no next action');
assert.equal(JSON.stringify(run('simPostNavigation(2)')),JSON.stringify({previous:null,next:null}),'Unavailable posts cannot navigate to arbitrary positions');
console.log('Simulator checks passed: reorder preserves interactions, empty/cancelled drops, likes and story sequences.');
