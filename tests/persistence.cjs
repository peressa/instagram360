const {readFileSync}=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const create=vm.runInNewContext(readFileSync('dist/persistence.js','utf8')+';createLocalPersistence');
const journal=new Map();
const storage={getItem:k=>journal.get(k)||null,setItem:(k,v)=>journal.set(k,v),removeItem:k=>journal.delete(k)};
const transactions=[];let failStart=false;let namespace='test';let status;
const database={transaction(){if(failStart)throw Error('Quota');const tx={objectStore:()=>({put(){}})};transactions.push(tx);return tx;}};
const writer=create({getDatabase:()=>database,getNamespace:()=>namespace,storage,onStatus:s=>status=s});
const key='rio360_draft_test_layout';
(async()=>{
  const first=writer.put('state',{key:'layout',tiles:[{imgId:'one'}]});
  assert.ok(journal.has(key),'Recovery draft exists synchronously, before IndexedDB commits');
  assert.equal(status.pending,1);
  const newer=writer.put('state',{key:'layout',tiles:[{imgId:'two'}]});
  transactions.shift().oncomplete();await first;
  assert.equal(JSON.parse(journal.get(key)).tiles[0].imgId,'two','An older completion must not discard a newer edit');
  transactions.shift().onabort();assert.equal(await newer,false);assert.equal(status.failed,true);
  assert.equal(writer.drafts()[0].tiles[0].imgId,'two','Aborted writes remain recoverable');
  const recovered=writer.recover();transactions.shift().oncomplete();assert.equal(await recovered,1);writer.resetError();
  assert.equal(journal.has(key),false);assert.equal(status.failed,false);
  failStart=true;assert.equal(await writer.put('state',{key:'layout',tiles:[]}),false);assert.equal(status.failed,true);failStart=false;
  const oldSet=storage.setItem;storage.setItem=()=>{throw Error('localStorage full')};
  const fallback=writer.put('state',{key:'layout',tiles:[{imgId:'latest'}]});transactions.shift().oncomplete();assert.equal(await fallback,true);
  assert.equal(journal.has(key),false,'A stale recovery draft cannot override a successful write after journal quota failure');storage.setItem=oldSet;
  namespace='other';const isolated=writer.put('state',{key:'profile',data:{name:'Other'}});assert.ok(journal.has('rio360_draft_other_profile'));transactions.shift().oncomplete();await isolated;
  assert.equal(status.pending,0);
  console.log('Persistence checks passed: immediate recovery, concurrent edits, transaction abort, retry, quota fallback and profile isolation.');
})().catch(error=>{console.error(error);process.exitCode=1});
