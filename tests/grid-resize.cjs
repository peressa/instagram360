const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync('dist/index.html', 'utf8');
const source = html.slice(html.indexOf('function resizedGridTiles('), html.indexOf('function setRows('));
const resize = vm.runInNewContext(source + '; resizedGridTiles');
const tile = id => ({imgId: id, z: 1.2, panX: .1, caption: 'Texto ' + id});
const ids = items => Array.from(items.filter(Boolean), t => t.imgId);
const first = Array(18).fill(null);
first.splice(0, 3, tile('a'), tile('b'), tile('c'));
const reduced = resize(first, 9);
assert.equal(reduced.length, 9);
assert.deepEqual(ids(reduced), ['a', 'b', 'c']);
assert.equal(reduced[0], first[0], 'Preserve crop and post metadata');
assert.equal(first.length, 18, 'Do not mutate undo history');
const bottom = Array(18).fill(null);
bottom.splice(15, 3, tile('a'), tile('b'), tile('c'));
assert.deepEqual(ids(resize(bottom, 9)), ['a', 'b', 'c']);
const scattered = Array(27).fill(null);
[0, 4, 8, 12, 16, 20, 24].forEach((at, i) => scattered[at] = tile(String(i)));
assert.deepEqual(ids(resize(scattered, 9)), ['0','1','2','3','4','5','6']);
assert.equal(resize(Array.from({length:18}, (_,i) => tile(String(i))), 9), null);
assert.equal(resize(Array(18).fill(null), 9).length, 9);
assert.deepEqual(ids(resize(reduced, 18)), ['a', 'b', 'c']);
const panorama = Array(18).fill(null);
for (let i = 12; i < 15; i++) panorama[i] = {...tile('p' + i), banner: {row:4}};
const resizedPanorama = resize(panorama, 9);
assert.deepEqual(ids(resizedPanorama), ['p12','p13','p14']);
assert.ok(resizedPanorama.slice(0,3).every(t => t.banner));
console.log('Grid resize regression checks passed: top, bottom, scattered, capacity, empty, expand, panorama, metadata and undo safety.');
